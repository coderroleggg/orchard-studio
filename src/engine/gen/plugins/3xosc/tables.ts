// 3x Osc (FL: 3x Osc): constant tables, bit-exact with FL Studio 2026 on macOS.
//
// - FL's host wavetables (TFruityPlugHost.WaveTables[0..5], 16384 floats
//   each: sine, triangle, square, saw, "analog" (rounded) saw, noise), which
//   the non-HQ oscillators read with a 32-bit phase (index = phase >>> 18).
//   FL builds them in FLEngine (generator at 0x43cbc0 in 26.1.6); this is that
//   code, verified bit for bit against FLEngine by the test host's
//   `tablecheck`. The noise table comes from FL's own Mersenne Twister port,
//   whose second twist loop starts one index early and reads the index field
//   as mt[-1] (replicated). (src/engine/dsp/flwavetables.ts lacks that quirk
//   and the rounded saw, so 3x Osc keeps its own copy.)
// - The release declick of FL's built-in voice engine (the "out" fade of the
//   channel sampler code linked into 3x Osc: type 3, 10 ms, built once at
//   44100 Hz when the plugin is created, so it is 441 samples at every sample
//   rate): t[i] = (cos((i + 1) * pi / 442) + 1) / 2 computed with
//   ippsVectorSlope_32f / ippsMulC_32f_I / ippsCos_32f_A11 / ippsAddC_32f, i.e.
//   Accelerate's vvcosf on macOS (FL's dsp_ippv2 library). vvcosf is not
//   correctly rounded (85 of the 441 entries differ from a correctly rounded
//   cosine by an ulp), so the table is FL's values as computed on macOS.

export const WAVE_SIZE = 16384;

function buildWaveTables(): Float32Array[] {
  const N = WAVE_SIZE;
  const kInvN = 6.103515625e-05; // 1 / 16384
  const W = [0, 1, 2, 3, 4, 5].map(() => new Float32Array(N));
  for (let i = 0; i < N; i++) W[0][i] = Math.sin(((i * 2) * Math.PI) * kInvN);
  for (let i = 0; i < N / 2; i++) W[1][(i + 12288) % N] = -1.0 + (i * 4) * kInvN;
  for (let i = N / 2; i < N; i++) W[1][(i + 12288) % N] = 1.0 - ((i - N / 2) * 4) * kInvN;
  for (let i = 0; i < N; i++) W[2][i] = i < N / 2 ? 1 : -1;
  for (let i = 0; i < N; i++) W[3][i] = -1.0 + (i * 2) * kInvN;
  // "analog saw": 7600 samples of an exponential rise in 16-bit steps, then +1, then -1
  let s2 = 32767;
  for (let i = 0; i < 7600; i++) {
    let s0 = Math.fround(s2 * 2);
    s0 = Math.fround(32767 - s0);
    const v = ((Math.trunc(s0) << 16) >> 16); // (int16)(int64)(double)s0
    W[4][i] = v / 32767.0;
    s2 = Math.fround(s2 * 0.997);
  }
  for (let i = 7600; i < 13653; i++) W[4][i] = 1;
  for (let i = 13653; i < N; i++) W[4][i] = -1;
  // FL's Mersenne Twister port (seed 19650218) with its off-by-one twist
  const mt = new Uint32Array(624);
  mt[0] = 19650218;
  for (let k = 1; k < 624; k++) mt[k] = (Math.imul(1812433253, (mt[k - 1] ^ (mt[k - 1] >>> 30)) >>> 0) + k) >>> 0;
  let mti = 624;
  const mag = (y: number) => (y & 1 ? 0x9908b0df : 0);
  const next = (): number => {
    if (mti >= 624) {
      let y: number;
      for (let kk = 0; kk <= 226; kk++) {
        y = (mt[kk] & 0x80000000) | (mt[kk + 1] & 0x7fffffff);
        mt[kk] = mt[kk + 397] ^ (y >>> 1) ^ mag(y);
      }
      for (let kk = 226; kk < 623; kk++) {
        y = (mt[kk] & 0x80000000) | (mt[kk + 1] & 0x7fffffff);
        const back = kk >= 227 ? mt[kk - 227] : mti;
        mt[kk] = back ^ (y >>> 1) ^ mag(y);
      }
      y = (mt[623] & 0x80000000) | (mt[0] & 0x7fffffff);
      mt[623] = mt[396] ^ (y >>> 1) ^ mag(y);
      mti = 0;
    }
    let y = mt[mti++];
    y ^= y >>> 11;
    y ^= (y << 7) & 0x9d2c5680;
    y ^= (y << 15) & 0xefc60000;
    y ^= y >>> 18;
    return y >>> 0;
  };
  for (let i = 0; i < N; i++) W[5][i] = next() * 2.3283064370807974e-10 * 2.0 - 1.0;
  return W;
}

