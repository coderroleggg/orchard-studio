/** Side-signal gain W of a separation knob value (-1000..1000). */
export function dxSepWidth(raw: number): number {
  const v = raw > 1000 ? 1000 : raw < -1000 ? -1000 : raw === raw ? raw : 0;
  return v < 0 ? 1 - v / 1000 : (5 - Math.pow(5, v / 1000)) / 4;
}

/** |H(jx)|^2 of n2 p^2 + n1 p + n0 over p^2 + d1 p + 1 at normalised frequency x. */
function amag2(n2: number, n1: number, n0: number, d1: number, x: number): number {
  const x2 = x * x;
  const nr = n0 - n2 * x2, ni = n1 * x, dr = 1 - x2, di = d1 * x;
  return (nr * nr + ni * ni) / (dr * dr + di * di);
}

/**
 * Magnitude-matched biquad (M. Vicanek, "Matched Second Order Digital Filters"):
 * poles by impulse invariance, numerator from the analog magnitude at DC, f0 and
 * Nyquist. Writes b0 b1 b2 a1 a2 to out[o..o+4].
 */
function designSection(kind: number, f: number, q: number, gainDb: number, fs: number, out: Float64Array, o: number): void {
  const A = Math.pow(10, gainDb / 40);
  const iq = 1 / Math.max(1e-6, q);
  let n2 = 0, n1 = 0, n0 = 1, d1 = iq;
  if (kind === HP) { n2 = 1; n0 = 0; }
  else if (kind === PK) { n2 = 1; n1 = A * iq; d1 = iq / A; }
  const f0 = Math.min(Math.max(f, 5), fs * 0.49);
  const w0 = (2 * Math.PI * f0) / fs;
  const zeta = d1 / 2;
  const e = Math.exp(-zeta * w0);
  const a1 = zeta <= 1 ? -2 * e * Math.cos(Math.sqrt(1 - zeta * zeta) * w0) : -2 * e * Math.cosh(Math.sqrt(zeta * zeta - 1) * w0);
  const a2 = e * e;
  const A0 = (1 + a1 + a2) * (1 + a1 + a2);
  const A1 = (1 - a1 + a2) * (1 - a1 + a2);
  const A2 = -4 * a2;
  const s = Math.sin(Math.min(w0, Math.PI * 0.99999) / 2);
  const phi1 = s * s, phi0 = 1 - phi1, phi2 = 4 * phi0 * phi1;
  const B0 = A0 * amag2(n2, n1, n0, d1, 0);
  const B1 = A1 * amag2(n2, n1, n0, d1, fs / 2 / f0);
  const Rc = (A0 * phi0 + A1 * phi1 + A2 * phi2) * amag2(n2, n1, n0, d1, 1);
  let B2 = (Rc - B0 * phi0 - B1 * phi1) / phi2;
  const sB0 = Math.sqrt(Math.max(0, B0)), sB1 = Math.sqrt(Math.max(0, B1));
  const W = 0.5 * (sB0 + sB1);
  if (W * W + B2 < 0) B2 = -W * W;
  const b0 = 0.5 * (W + Math.sqrt(W * W + B2));
  out[o] = b0;
  out[o + 1] = 0.5 * (sB0 - sB1);
  out[o + 2] = b0 !== 0 ? -B2 / (4 * b0) : 0;
  out[o + 3] = a1;
  out[o + 4] = a2;
}

/** One mono cascade: delay (read from the shared history) -> biquads -> gain. */
class Chain {
  readonly c = new Float64Array(MAXSEC * 5);
  readonly z = new Float64Array(MAXSEC * 2);
  n = 0;
  gain = 1;
  delay = 0;

  load(shape: readonly number[], gain: number, delay: number, fs: number): void {
    let k = 0;
    for (let i = 0; i + 3 < shape.length && k < MAXSEC; i += 4) {
      const kind = shape[i], f = shape[i + 1];
      if (kind !== HP && f >= fs * 0.475) continue; // above Nyquist: identity
      designSection(kind, f, shape[i + 2], shape[i + 3], fs, this.c, k * 5);
      k++;
    }
    this.n = k;
    this.gain = gain;
    this.delay = delay;
    this.z.fill(0);
  }

  reset(): void { this.z.fill(0); }

  run(x: Float64Array, n: number): void {
    const c = this.c, z = this.z;
    for (let s = 0; s < this.n; s++) {
      const o = s * 5;
      const b0 = c[o], b1 = c[o + 1], b2 = c[o + 2], a1 = c[o + 3], a2 = c[o + 4];
      let z1 = z[2 * s], z2 = z[2 * s + 1];
      for (let i = 0; i < n; i++) {
        const xi = x[i];
        const y = b0 * xi + z1;
        z1 = b1 * xi - a1 * y + z2;
        z2 = b2 * xi - a2 * y;
        x[i] = y;
      }
      // flush denormals; recover from anything non-finite
      z[2 * s] = z1 > 1e-30 || z1 < -1e-30 ? (z1 - z1 === 0 ? z1 : 0) : 0;
      z[2 * s + 1] = z2 > 1e-30 || z2 < -1e-30 ? (z2 - z2 === 0 ? z2 : 0) : 0;
    }
    const g = this.gain;
    for (let i = 0; i < n; i++) x[i] *= g;
  }
}

