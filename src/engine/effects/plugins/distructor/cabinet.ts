//
// FL convolves each channel with one of 55 cabinet impulse responses (4 of the
// 59 list entries are category headers). No impulse response is used here:
// every cabinet channel is a fitted cascade of magnitude-matched biquads (high
// pass / low pass / peaking analog prototypes, M. Vicanek's matched design,
// so there is no cramping near Nyquist) plus an absolute gain, a polarity and
// a pure delay. Only these fitted parameters are stored.
// Fitted to FL's measured responses (flfxhost, 44.1 kHz, one impulse per input
// channel, 1/6-octave power smoothing, 40 Hz..16 kHz, floor at peak - 60 dB):
// rms error 0.03..0.68 dB per path (median 0.13), max deviation 3.4 dB
// (per path figures in dxcab_notes.txt). The parameters were fitted so that
// the cascades designed at 44.1, 48 and 96 kHz all give the same response.
//
// Measured behaviour reproduced:
//  - every cabinet is dual-mono (no L<->R crosstalk). Stereo cabinets have
//    different L and R responses (and delays / polarities); mono cabinets use
//    one response for both channels. FL's per-cabinet normalisation gain is
//    part of the stored gain.
//  - category headers (0, 20, 27, 38) make the module an exact passthrough;
//    the stereo separation knobs are ignored there as well.
//  - signal flow: input separation -> per-channel cabinet -> output separation.
//    A separation value v (-1000..1000) scales the side signal:
//    L' = M + W S, R' = M - W S with M = (L + R) / 2, S = (L - R) / 2 and
//    W = 1 - v / 1000 for v < 0 ("separated", side x2 at -1000) and
//    W = (5 - 5^(v / 1000)) / 4 for v >= 0 ("merged", mono at +1000).
//  - FL plays the IR samples verbatim at every sample rate with gain 44100/sr
//    (no resampling: at 96 kHz the response is stretched 2.18x upwards in
//    frequency and 6.8 dB quieter). By default this class reproduces the
//    44.1 kHz response at any rate (frequencies in Hz, delays in ms); pass
//    flRateQuirk = true to emulate FL's rate dependence instead.
//  - separation changes ramp like FL: in every processed block of L samples W
//    moves linearly from its current value towards the target by at most
//    0.002 * L (first sample of the block = current value), at any rate.
// Changing the cabinet crossfades (20 ms) between the old and new cascades.
